module mod_Basis1D
  use precision, only: dp, i32
  implicit none
  private
  public :: Basis1D, xToB,BTox, genSVDBasis, SVDBasis, freeBasis1D

  type Basis1D
    !! Data type for storing vectors of a basis and integration weights for the space.
    integer :: n = 0 !! Number of basis vectors.
    integer :: Nx = 0 !! Number of grid points on which basis vectors are given.

    real(dp), allocatable :: basis(:,:) !! (Nx,n) Matrix of basis vectors.
    real(dp), allocatable :: xgrid(:) !! (Nx) values of the 1D argument space.
    real(dp), allocatable :: weights(:) !! (Nx) Integration weights to be used on xgrid.

  end type Basis1D


  interface xToB
    module procedure dxToB
    module procedure zxtoB
  end interface xToB

  interface Btox
    module procedure dBTox
    module procedure zBTox
  end interface Btox

contains

  subroutine freeBasis1D(Basis)
    type(Basis1D), intent(inout):: Basis

    if (allocated(Basis%basis)) deallocate(Basis%basis)
    if (allocated(Basis%xgrid)) deallocate(Basis%xgrid)
    if (allocated(Basis%weights)) deallocate (Basis%weights)
  end subroutine freeBasis1D

  function dxToB(Basis, f) result(koef)
    !! Get projection on to basis of f defined on xgrid
    type(Basis1D), intent(in) :: Basis
    real(dp), intent(in) :: f(Basis%Nx) !! Function f defined on xgrid to be projected.
    real(dp) :: koef(Basis%n) !! Coefficients of f in basis representation.
    real(dp) :: wf(Basis%Nx)
    wf = f * Basis%weights
    call dgemv('T', Basis%Nx, Basis%n, 1._dp, Basis%basis, Basis%Nx, wf, 1, 0._dp, koef, 1)
  end function dxToB

  function zxToB(Basis, f) result(koef)
    !! Get projection on to basis of f defined on xgrid
    type(Basis1D), intent(in) :: Basis
    complex(dp), intent(in) :: f(Basis%Nx) !! Function f defined on xgrid to be projected.
    complex(dp) :: koef(Basis%n) !! Coefficients of f in basis representation.
    real(dp) :: koef_re(Basis%n)
    real(dp) :: koef_im(Basis%n)
    real(dp) :: wf_re(Basis%Nx)
    real(dp) :: wf_im(Basis%Nx)
    wf_re = real(f, kind=dp) * Basis%weights
    wf_im = f%im * Basis%weights
    call dgemv('T',Basis%Nx, Basis%n,1._dp, Basis%basis, Basis%Nx, wf_re, 1, 0._dp, koef_re, 1)
    call dgemv('T',Basis%Nx, Basis%n,1._dp, Basis%basis, Basis%Nx, wf_im, 1, 0._dp, koef_im, 1)
    koef = cmplx(koef_re,koef_im,kind=dp)
  end function zxToB

  function dBTox(Basis, koef) result(f)
    !! Get function on xgrid from its basis representations coefficients.
    type(Basis1D), intent(in) :: Basis
    real(dp), intent(in) :: koef(Basis%n) !! Coefficients of f in basis representation.
    real(dp) :: f(Basis%Nx) !! Function f values on xgrid.
    integer :: i
    f = 0._dp
    do i= 1,Basis%n
      f = f + koef(i) * Basis%basis(:,i)
    end do
  end function dBTox

  function zBTox(Basis, koef) result(f)
    !! Get function on xgrid from its basis representations coefficients.
    type(Basis1D), intent(in) :: Basis
    complex(dp), intent(in) :: koef(Basis%n) !! Coefficients of f in basis representation.
    complex(dp) :: f(Basis%Nx) !! Function f values on xgrid.
    integer :: i
    f = cmplx(0._dp, kind=dp)
    do i= 1,Basis%n
      f = f + koef(i) * Basis%basis(:,i)
    end do
  end function zBTox


  subroutine genSVDBasis(Nx,A,weights,n,xgrid,work, lwork,Basis)
    !! Generate a basis from the n most significant components of SVD of weighted matrix A.
    integer, intent(in) :: Nx !! Rows of A.
    integer, intent(in) :: n !! How many vectors to keep from SVD
    real(dp), intent(inout) :: A(:,:) !! (Nx, N >=n) A matrix of vectors to be approximated by SVD.
    real(dp), intent(in) :: weights(Nx) !! Weights to be used on the rows of A.
    real(dp), intent(in) :: xgrid(Nx) !! Grid on which the functions of array A are given.
    real(dp), allocatable, intent(inout) :: work(:) !! Helper array to use for calculations.
    integer(i32), intent(inout) :: lwork !! length of work array; if lwork=-1, work is allocated to necessary length.
    type(Basis1D), intent(out) :: Basis !! The basis generated by this routine.
    real(dp) :: sqrtweights(Nx)
    integer :: i ! loop counter

    Basis%n = n
    Basis%Nx = Nx
    if (allocated(Basis%basis)) deallocate(Basis%basis)
    allocate(Basis%basis(Nx,n))
    if (allocated(Basis%xgrid)) deallocate(Basis%xgrid)
    allocate(Basis%xgrid(Nx))
    if (allocated(Basis%weights)) deallocate(Basis%weights)
    allocate(Basis%weights(Nx))

    Basis%weights = weights
    Basis%xgrid = xgrid

    ! Apply the weighting before performing SVD
    sqrtweights = sqrt(weights)
    do i = 1, size(A, dim=2)
      A(:,i) = sqrtweights * A(:,i)
    end do

    ! Perform the SVD
    call SVDBasis(A,work,lwork)

    do i=1, n
      Basis%basis(:,i) = A(:,i) / sqrtweights
    end do

  end subroutine genSVDBasis

  subroutine SVDBasis(A, work, lwork)
    !! Returns an SVD basis for approximating given functions.
    real(dp), intent(inout) :: A(:, :) !! Matrix of column vectors to be approximated.
    !! Output: Matrix of SVD approximation basis vectors.
    real(dp), allocatable, intent(inout) :: work(:) !! Helper array to use for calculations.
    integer(i32), intent(inout) :: lwork !! length of work array; if lwork=-1, work is allocated to necessary length.
    real(dp) :: dummy(1, 1)
    integer(i32) :: d1, d2 ! dimensions of matrix A
    real(dp), allocatable :: S(:) ! Stores the singular values of matrix A
    integer(i32) :: info ! Diagnostic output from SVD calculation routine

    d1 = size(A, dim=1)
    d2 = size(A, dim=2)
    allocate (S(min(d1, d2)))
    ! Make sure work array is allocated properly
    if (lwork == -1) then
      if (allocated(work)) then
        deallocate (work)
      end if
      allocate (work(1))
      ! Determine needed length of WORK
      call dgesvd('O', 'N', d1, d2, A, d1, S, dummy, 1, dummy, 1, work, -1, info)
      lwork = int(work(1))
      deallocate (work)
      allocate (work(lwork))
    end if

    ! Compute the SVD
    call dgesvd('O', 'N', d1, d2, A, d1, S, dummy, 1, dummy, 1, work, lwork, info)
  end subroutine SVDBasis

end module mod_Basis1D
